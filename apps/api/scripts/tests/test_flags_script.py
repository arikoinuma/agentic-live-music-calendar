"""Tests for `scripts/flags.py`: the table, the effective values, the TypeScript it generates (C3.1-T13).

HOW TO READ THIS
  The script renders the registry for people (`registry_table`, `effective_report`) and for the web code base
  (`render_ts`). The checks it runs are tested in `app/tests/test_flag_hygiene.py`. Expected text is written out
  here by hand from the plan (C3.1-D17, C3.1-D18); the committed `flag-registry.ts` is compared with a fresh render, a
  quick local mirror of `make contract-check`.
"""

import pytest

from app.flags import FLAGS, env_key
from app.tests.test_flags import CASE_FLAGS
from scripts.flags import TS_OUT, effective_report, main, registry_table, render_ts


def test_the_table_lists_every_flag_with_its_owner_and_removal_condition() -> None:
    # Proves (C3.1-T13, C3.1-D18): `make flags` shows, for each flag, the name, variable, scope, surfaces, default,
    # owner, creation date and the condition for deleting it, so a flag with no way out is visible. Expected
    # fragments are the registry entry's, written by hand.
    table = registry_table(FLAGS)
    assert "worker.scheduled_runs  (FLAG_WORKER_SCHEDULED_RUNS)" in table
    assert "scope: environment" in table and "surfaces: python" in table and "default: false" in table
    assert "owner: Ari" in table and "created: 2026-11-09" in table
    assert "removal: Delete the flag and the gate" in table


def test_effective_reports_a_default_and_a_set_value_with_their_sources() -> None:
    # Proves (C3.1-T13): an unset flag reads `default` and a set one reads `environment`, so "where did this value
    # come from" has an answer on a Railway shell. Needs `resolve_value` (C3.1-K1) to be filled in.
    assert effective_report(FLAGS, {}) == "worker.scheduled_runs = false   (default)"
    assert effective_report(FLAGS, {"FLAG_WORKER_SCHEDULED_RUNS": "true"}) == (
        "worker.scheduled_runs = true   (environment)"
    )


def test_effective_refuses_to_report_a_bad_environment() -> None:
    # Proves (C3.1-T13, C3.1-D12): a value `Settings` would refuse at startup is not reported as an effective
    # value. It raises with the startup problem, which the command line turns into exit status 1.
    with pytest.raises(ValueError, match="FLAG_WORKER_SCHEDULED_RUNS"):
        effective_report(FLAGS, {"FLAG_WORKER_SCHEDULED_RUNS": "yes"})


def test_the_generated_typescript_for_the_real_registry() -> None:
    # Proves (C3.1-T13, C3.1-D17): the one registered flag appears as a literal with its scope, surfaces and
    # default, and `WebFlagName` is `never` because no flag has the web surface: `isEnabled("worker.scheduled_runs")`
    # must not type-check. The fragments are the plan's, written by hand.
    text = render_ts(FLAGS)
    assert text.startswith("// GENERATED by apps/api/scripts/flags.py")
    assert (
        '  "worker.scheduled_runs": {\n    scope: "environment",\n    surfaces: ["python"],\n    default: false,\n  },'
        in text
    )
    assert "export type FlagName = keyof typeof FLAG_REGISTRY;" in text
    assert "export type WebFlagName = never;" in text


def test_the_generated_typescript_names_the_web_readable_flags() -> None:
    # Proves (C3.1-T13, C3.1-D17): with the case table's registry, `WebFlagName` is the union of exactly the flags
    # declaring the web surface, in registry order (the table's: scoped, web_only, unread), and not the Python-only one.
    text = render_ts(CASE_FLAGS)
    assert 'export type WebFlagName = "demo.scoped" | "demo.web_only" | "demo.unread";' in text
    assert '  "demo.python_only": {\n    scope: "environment",\n    surfaces: ["python"],' in text
    assert '  "demo.scoped": {\n    scope: "metro",\n    surfaces: ["python", "web"],' in text


def test_the_committed_typescript_is_what_the_generator_writes() -> None:
    # Proves (C3.1-T13, C3.1-D17): `lib/flag-registry.ts` is not hand-edited and not stale. `make contract-check`
    # checks the same in CI; this is the quick local mirror.
    assert TS_OUT.read_text() == render_ts(FLAGS)


def test_the_command_line_prints_the_table_and_checks_clean(capsys: pytest.CaptureFixture[str]) -> None:
    # Proves (C3.1-T13): `python -m scripts.flags` with no mode prints the table, and `--check` over the real
    # repository exits 0 and says how many flags it saw (the hygiene rules themselves are in test_flag_hygiene.py).
    assert main([]) == 0
    assert env_key("worker.scheduled_runs") in capsys.readouterr().out
    assert main(["--check"]) == 0
    assert "1 feature flag(s) registered" in capsys.readouterr().out
